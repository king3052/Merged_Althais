"""
billing_registry.py: the versioned registry of what billing activation needs, per payer workflow.

Every requirement has a documented source and its dependencies. Nothing here is generated by AI, and AI never adds
to it: a person edits this file, bumps VERSION, and fills in REVIEW once someone has checked the entries against the
sources. Until then the screens say the registry hasn't been reviewed, and clinics should confirm details with each
payer. Payer rules change; this file records what we could source, not a promise about any payer's process.

Scopes (where a requirement's status is stored):
  clinic     the practice as a whole (its authorization, its clearinghouse account)
  entity     the billing entity (the Tax ID / organization NPI that gets paid)
  provider   one rendering practitioner (individual NPI)
  location   one service location
  payer      the requirement applies per payer (combined with entity or provider scope)

Tracks (kept separate on purpose, because each moves on its own timeline):
  identity       NPI / Tax ID / license facts
  authorization  the clinic's own approval for Althais to act
  enrollment     payer provider/group enrollment
  credentialing  payer credentialing
  contracting    payer participation agreement (in-network)
  edi            electronic claim (837P) submission enrollment
  era            electronic remittance (835) enrollment (payment, doesn't block sending claims)
  eft            electronic funds transfer (payment, doesn't block sending claims)
  connectivity   the clinic's clearinghouse account and payer route
"""


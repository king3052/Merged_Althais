def payer_type(name: str) -> str:
    return KNOWN_PAYERS.get((name or "").strip().lower(), (name, "other"))[1]


def payer_key(name: str) -> str:
    n = (name or "").strip()
    return KNOWN_PAYERS.get(n.lower(), (n, ""))[0].lower().replace(" ", "_") or "unknown"


def for_payer(ptype: str) -> list:
    return [r for r in REQUIREMENTS if ptype in r["payerTypes"] and r["scope"] in ("entity", "provider") and r["track"] not in ("identity",)
            and r["id"] not in ("entity_w9",)]


def common(scope: str) -> list:
    """Requirements that don't depend on a payer (clinic, entity and provider identity)."""
    return [r for r in REQUIREMENTS if r["scope"] == scope and (r["track"] in ("identity", "authorization", "connectivity"))]
